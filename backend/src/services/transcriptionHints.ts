/**
 * hints 用に comma-separated 文字列を返す。
 * 引数の extra と TRANSCRIPTION_HINTS_EXTRA を両方 merge する。
 * TRANSCRIPTION_HINTS_LIMIT は debug 用の全体上限。
 */
export function buildHints(extraCsv = ""): string {
  const fromEnv = (process.env.TRANSCRIPTION_HINTS_EXTRA || "")
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
  const fromArg = extraCsv
    .split(",")
    .map((s) => s.trim())
    .filter(Boolean);
  const merged = [...HINTS, ...fromEnv, ...fromArg];
  const limitStr = process.env.TRANSCRIPTION_HINTS_LIMIT;
  const limit = limitStr ? Number(limitStr) : 500;
  return merged
    .slice(0, Number.isFinite(limit) ? limit : 500)
    .join(",");
}
